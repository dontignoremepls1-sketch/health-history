export function geneticDisplayTitle(value) {
  const title = typeof value === 'string' ? value : String(value?.title || '');
  return Object.hasOwn(GENETIC_TITLE_ALIASES,title) ? GENETIC_TITLE_ALIASES[title] : title;
}
export function geneticAliasSearchText(value) {
  const title = typeof value === 'string' ? value : String(value?.title || '');
  return `${geneticDisplayTitle(title)} ${title}`;
}
export function geneticCategoryLabel(value) { return Object.hasOwn(categoryAliases,value) ? categoryAliases[value] : value; }
